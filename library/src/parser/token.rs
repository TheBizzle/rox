use crate::core::source_loc::SourceLoc;

#[derive(Clone, Debug)]
pub struct Token {
  pub loc: SourceLoc,
  pub typ: TokenType,
}

#[derive(Clone, Debug, PartialEq)]
pub enum TokenType {
  And,
  Bang,
  BangEqual,
  Class,
  Comma,
  Dot,
  Else,
  Eof,
  Equal,
  EqualEqual,
  False,
  For,
  Fun,
  Greater,
  GreaterEqual,
  Identifier(String),
  If,
  LeftBrace,
  LeftParen,
  Less,
  LessEqual,
  LoxString(String),
  Minus,
  Nil,
  Number(f64),
  Or,
  Plus,
  Print,
  Return,
  RightBrace,
  RightParen,
  Semicolon,
  Slash,
  Star,
  Super,
  This,
  True,
  Var,
  While,
}
